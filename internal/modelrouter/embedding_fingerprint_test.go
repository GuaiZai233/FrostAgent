package modelrouter

import (
	"testing"

	"github.com/GuaiZai233/FrostAgent/internal/provider/llm/api"
)

func TestEmbeddingFingerprintEffectiveRoute(t *testing.T) {
	target := Target{EndpointID: "synthetic-endpoint", BaseURL: "https://relay.invalid/v1", UpstreamModel: "embed", MaxInputTokens: 8192}
	for _, base := range []string{"https://relay.invalid", "https://relay.invalid/v1/", "https://relay.invalid/proxy%2Froute?region=fixture"} {
		t.Run(base, func(t *testing.T) {
			chat, responses := target, target
			chat.BaseURL, chat.APIFormat = base, string(api.ChatCompletions)
			responses.BaseURL, responses.APIFormat = base, string(api.Responses)
			if EmbeddingFingerprint(chat) != EmbeddingFingerprint(responses) {
				t.Fatal("chat-only format change invalidated embedding fingerprint")
			}
			route, err := api.ChatCompletions.URL(base, "embeddings", "embed")
			if err != nil {
				t.Fatal(err)
			}
			custom := chat
			custom.BaseURL, custom.APIFormat = route, string(api.Custom)
			if EmbeddingFingerprint(chat) != EmbeddingFingerprint(custom) {
				t.Fatal("equivalent custom embedding route changed fingerprint")
			}
		})
	}
	// Fixture generated by the pre-format implementation; keep existing indexes usable.
	const legacyFingerprint = "a5b547ccc0f789578c7c1297f15c30a79a6a8dcde2e956e18bae112fb72b9140"
	if got := EmbeddingFingerprint(target); got != legacyFingerprint {
		t.Fatalf("legacy fingerprint changed: %s", got)
	}
	for _, format := range []api.Format{api.ChatCompletions, api.Responses} {
		same := target
		same.BaseURL, same.APIFormat = "https://relay.invalid", string(format)
		if EmbeddingFingerprint(same) != legacyFingerprint {
			t.Fatal("equivalent versioned route lost legacy fingerprint")
		}
	}
	for _, change := range []func(*Target){
		func(v *Target) { v.BaseURL = "https://other.invalid/v1" },
		func(v *Target) { v.UpstreamModel = "other-embed" },
		func(v *Target) { v.MaxInputTokens++ },
		func(v *Target) { v.EndpointID = "other-endpoint" },
		func(v *Target) { v.BaseURL = "https://relay.invalid" },
		func(v *Target) {
			v.BaseURL = "https://relay.invalid/v1/embeddings?region=other"
			v.APIFormat = string(api.Custom)
		},
		func(v *Target) { v.BaseURL = "https://relay.invalid/exact"; v.APIFormat = string(api.Custom) },
		func(v *Target) { v.APIFormat = string(api.Anthropic) },
		func(v *Target) { v.APIFormat = string(api.Gemini) },
	} {
		changed := target
		change(&changed)
		if EmbeddingFingerprint(changed) == legacyFingerprint {
			t.Fatalf("changed embedding semantics reused fingerprint: %+v", changed)
		}
	}
	custom := target
	custom.APIFormat, custom.BaseURL = string(api.Custom), "https://relay.invalid/exact"
	trailing := custom
	trailing.BaseURL += "/"
	if EmbeddingFingerprint(custom) == EmbeddingFingerprint(trailing) {
		t.Fatal("distinct exact URLs shared a fingerprint")
	}
}
