// extractPrompt 是发送给 LLM 的私聊记忆提取提示词。
// {conversation} 会被替换为最近的对话内容。
const extractPrompt = `请从以下对话中提取值得长期记住的信息。
当前系统时间：{current_time}
返回 JSON 数组，每条包含：
- content: 自然语言描述（简洁、独立可理解）
- tags: 关键词标签数组（2-5个），只使用用户原文明确出现或明确确认的主题、实体、别名、缩写和同义词。固定名称保持完整，不要拆分术语。

事实来源约束（必须严格遵守）：
- 只有 [user] 消息中由用户明确陈述的内容，才可以作为新记忆的事实依据。
- [assistant] 消息只用于理解对话上下文，一律视为未经验证的内容。不得提取仅由助手提出的事实、猜测、解释、联想或结论。
- 不得使用你自身已有的知识补全对话，不得根据谐音、翻译、常识、上下文联想或相似名称推断用户没有亲自说出的实体关系、别名或结论。
- 含有“可能”“应该”“也许”“大概”“猜测”等不确定表达的内容，不得作为确定事实提取。
- 如果一项信息只出现在 [assistant] 消息中，或者无法从 [user] 原文直接得到，必须忽略。拿不准时返回空数组 []，不要猜测。

提取标准：
- 用户的身份信息（名字、职业、偏好等）
- 重要的事实和决定
- 长期有效的偏好或习惯
- 时间敏感的信息应在 content 中记录明确日期，不要使用相对时间
- 不要提取：临时性的闲聊、一次性的请求、客观知识

如果没有任何值得记住的信息，返回空数组 []。
只返回 JSON，不要其他文字。

对话内容：
{conversation}`

// extractGroupPrompt 是发送给 LLM 的群聊模型回合记忆提取提示词。
const extractGroupPrompt = `请从以下群聊对话中提取值得长期记住的群聊信息。
当前系统时间：{current_time}
当前发言成员：{speaker_name}（QQ：{speaker_id}）

返回 JSON 数组，每条包含：
- content: 自然语言描述（简洁、独立可理解）
- tags: 关键词标签数组（2-5个），包含主体人名、实体、主题等。固定名称保持完整，不要拆分术语。
- evidence: 字符串，当前发言成员亲口陈述该事实的原文文字片段（必须直接摘录自用户发言原文，不可臆造）
- is_self: 布尔值。当且仅当当前发言者亲口明确陈述关于自己（第一人称）的长期事实（如“我喜欢打羽毛球”、“我是程序员”）时为 true。如果涉及他人、转述他人（如“小红说小明喜欢披萨”）、群规、多人关系或客观事实，必须为 false！

事实归属与陈述规范（严格执行）：
1. 第一人称自述：如果当前发言者明确自述关于自己的长期事实，is_self 设为 true，并在 evidence 中给出原文摘录。
2. 第三方转述或陈述他人：如果发言者提及他人（例如“小红说小明喜欢披萨”），is_self 必须为 false！content 必须明确归属来源（例如“小红称小明喜欢披萨”），tags 中必须包含涉及的主体人名（如 ["小红", "小明", "披萨"]）。严禁捏造或猜测第三方身份。
3. 群规与多人关系：群规、活动约定、公共规则、多人互动事实，is_self 必须为 false。
4. 事实来源约束：只有真实群友明确发言的内容可作为事实依据；不得提取由机器人/助手单方面提出的事实或猜测。
5. 临时闲聊、即时情绪、一次性请求不得提取。

如果没有任何值得记住的信息，返回空数组 []。
只返回 JSON，不要其他文字。

对话内容：
{conversation}`

