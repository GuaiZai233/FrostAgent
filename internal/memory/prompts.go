package memory

// extractPrompt 是发送给 LLM 的记忆提取提示词。
// {conversation} 会被替换为最近的对话内容（最后一轮用户/助手发言，加上
// 上一轮用户/助手发言作为纠错上下文）。
const extractPrompt = `请从以下对话中提取值得长期记住的信息。
返回 JSON 数组，每条包含：
- content: 自然语言描述（简洁、独立可理解）
- tags: 关键词标签数组（2-5个），应包括主题、实体以及确定的常用别名、缩写和同义词。固定名称保持完整，不要拆分术语。
- visibility: "private"（个人信息）或 "public"（公共知识）

提取标准：
- 用户的身份信息（名字、职业、偏好等）
- 重要的事实和决定
- 长期有效的偏好或习惯
- 如果用户正在纠正或更新之前的事实（例如"X 其实是指 Y"），输出一条反映**更正后**内容的新记忆——错误版本会在后续反思时被清理。
- 不要提取：临时性的对话、闲聊、一次性的请求
- 不要重复提取本对话之前已经形成的稳定事实

注意：对话中可能包含上一轮的用户/助手发言，作为当前轮是否在纠正之前事实的参考。识别纠错的关键是看当前轮是否在否定、修正或重新定义上一轮的内容。

如果没有任何值得记住的信息，返回空数组 []。
只返回 JSON，不要其他文字。

对话内容：
{conversation}`
